//! SUPPLY-07 (CI Python tools): every requirement is pinned with `==` and carries
//! sha256 hashes, and nothing else (index, URL, editable, nested file) is accepted.
//! The check runs in Rust before uv is invoked.

use std::fs;
use std::path::PathBuf;

use up_dev::python_tools::check_requirements_lock;

const H1: &str = "09e5f29531daab93366bb061e76019d5e91691ef0a40328f04c927387d1d364d";
const H2: &str = "fc394a5b3be980a4062607b8fdddc0843f4fa394152b6da21722f5d59013c220";

fn repo_root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(|p| p.parent())
        .expect("workspace root")
        .to_path_buf()
}

fn messages(text: &str) -> String {
    check_requirements_lock(text)
        .expect_err("lock must be rejected")
        .messages
        .join("\n")
}

#[test]
fn test_supply_07_ci_requirement_without_hash_rejected() {
    let msg = messages("yamllint==1.38.0\n");
    assert!(msg.contains("SUPPLY-07"), "{msg}");
    assert!(msg.contains("yamllint"), "{msg}");
    assert!(msg.contains("hash"), "{msg}");
}

#[test]
fn test_supply_07_ci_unpinned_requirement_rejected() {
    let msg = messages(&format!("yamllint>=1.38 \\\n    --hash=sha256:{H1}\n"));
    assert!(msg.contains("SUPPLY-07"), "{msg}");
    assert!(msg.contains("yamllint"), "{msg}");
    let msg = messages(&format!("yamllint~=1.38.0 \\\n    --hash=sha256:{H1}\n"));
    assert!(msg.contains("yamllint"), "{msg}");
    let msg = messages(&format!("yamllint \\\n    --hash=sha256:{H1}\n"));
    assert!(msg.contains("yamllint"), "{msg}");
}

#[test]
fn test_supply_07_ci_index_and_url_entries_rejected() {
    let hashed = format!("yamllint==1.38.0 \\\n    --hash=sha256:{H1}\n");
    for bad in [
        "--index-url https://example.invalid/simple",
        "--extra-index-url https://example.invalid/simple",
        "--find-links https://example.invalid/wheels",
        "-e .",
        "-r other.txt",
        "pkg @ https://example.invalid/pkg.whl",
        "https://example.invalid/pkg.whl",
    ] {
        let text = format!("{hashed}{bad}\n");
        let msg = messages(&text);
        assert!(msg.contains("SUPPLY-07"), "{bad}: {msg}");
        // The offending line (number 3) is named.
        assert!(
            msg.contains("line 3") || msg.contains(":3:"),
            "{bad}: {msg}"
        );
    }
    // The same entries are rejected when they come first.
    messages("--index-url https://example.invalid/simple\n");
}

#[test]
fn test_supply_07_ci_malformed_hash_rejected() {
    for bad in [
        "--hash=sha256:ABC",
        "--hash=md5:d41d8cd98f00b204e9800998ecf8427e",
        &format!("--hash=sha256:{}", H1.to_uppercase()),
        &format!("--hash=sha256:{}0", H1),
    ] {
        let msg = messages(&format!("yamllint==1.38.0 \\\n    {bad}\n"));
        assert!(
            msg.contains("yamllint") || msg.contains("line"),
            "{bad}: {msg}"
        );
    }
}

#[test]
fn test_supply_07_ci_hashed_entry_accepted() {
    let text = format!(
        "# This file was autogenerated by uv\n\
         #    uv pip compile ...\n\
         yamllint==1.38.0 \\\n\
         \x20   --hash=sha256:{H1} \\\n\
         \x20   --hash=sha256:{H2}\n\
         \x20   # via\n\
         \x20   #   -r tools/ci-requirements.in\n\
         \x20   #   ansible-lint\n\
         \n\
         pycparser==3.11 ; implementation_name != 'PyPy' \\\n\
         \x20   --hash=sha256:{H1}\n\
         \x20   # via cffi\n"
    );
    check_requirements_lock(&text).expect("hashed entries pass");
}

#[test]
fn test_supply_07_ci_empty_lock_rejected() {
    let msg = messages("# only a comment\n\n");
    assert!(msg.contains("SUPPLY-07"), "{msg}");
}

#[test]
fn test_supply_07_ci_requirements_lock_is_fully_hashed() {
    let path = repo_root().join("tools/ci-requirements.txt");
    let text = fs::read_to_string(&path).expect("tools/ci-requirements.txt exists");
    check_requirements_lock(&text).expect("committed lock passes the pre-check");
    for pin in [
        "yamllint==1.38.0",
        "ansible-lint==26.10.1",
        "zizmor==1.31.1",
        "check-jsonschema==0.38.2",
    ] {
        assert!(
            text.lines().any(|l| l.starts_with(pin)),
            "lock must contain {pin}"
        );
    }
}
